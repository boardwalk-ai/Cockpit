-- notes_db — Phase 1: Typewriter blocks, Magic Pencil ink, sync bookkeeping.
--
-- Sync model: every row carries `revision` (per-row optimistic concurrency) and
-- `layer_rev` (the session layer's monotonic counter at its last change), so a
-- client catches up with `?sinceRev=` and never re-downloads the whole note.

-- Monotonic revision per (session, layer): blocks, ink, transcript, …
CREATE TABLE session_layer_revs (
    session_id  uuid NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    layer       text NOT NULL,
    rev         bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (session_id, layer)
);

-- Results of ops already applied, keyed by the client's op id, so an offline
-- client replaying its queue changes nothing the second time.
CREATE TABLE applied_ops (
    session_id    uuid NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    client_op_id  text NOT NULL,
    result        jsonb NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (session_id, client_op_id)
);

CREATE TABLE blocks (
    id                     uuid PRIMARY KEY,           -- generated by the client
    session_id             uuid NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    user_id                uuid NOT NULL,
    section_id             uuid,
    -- Fractional index (base62); ordered byte-wise so inserts never renumber.
    position               text COLLATE "C" NOT NULL,
    type                   text NOT NULL CHECK (type IN (
                               'paragraph', 'h1', 'h2', 'h3', 'bulleted', 'numbered', 'checklist', 'quote',
                               'definition', 'keyIdea', 'formula', 'example', 'question', 'examHint',
                               'warning', 'assignment', 'summary', 'table', 'image', 'diagram', 'slideRef',
                               'pdfExcerpt', 'transcriptExcerpt', 'audioTimestamp', 'divider')),
    text                   text NOT NULL DEFAULT '',
    checked                boolean NOT NULL DEFAULT false,
    indent                 integer NOT NULL DEFAULT 0 CHECK (indent BETWEEN 0 AND 8),
    origin                 text NOT NULL DEFAULT 'student' CHECK (origin IN (
                               'student', 'aiInsertedByStudent', 'fromInk', 'fromTranscript', 'fromSlide')),
    device_id              uuid,
    audio_ts_ms            bigint,
    transcript_anchor      jsonb,
    source_ref             jsonb,
    ai_sources             jsonb NOT NULL DEFAULT '[]'::jsonb,
    topic_links            text[] NOT NULL DEFAULT '{}',
    assignment_links       text[] NOT NULL DEFAULT '{}',
    study_studio_selected  boolean NOT NULL DEFAULT false,
    revision               bigint NOT NULL DEFAULT 1,
    layer_rev              bigint NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    deleted_at             timestamptz
);
CREATE INDEX idx_blocks_order ON blocks (session_id, position, id) WHERE deleted_at IS NULL;
CREATE INDEX idx_blocks_sync ON blocks (session_id, layer_rev);
CREATE TRIGGER trg_blocks_updated BEFORE UPDATE ON blocks
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Full snapshot of a block after every change: history, restore-deleted, and
-- the server side of "keep both" conflicts.
CREATE TABLE block_revisions (
    id          bigserial PRIMARY KEY,
    block_id    uuid NOT NULL,
    session_id  uuid NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    user_id     uuid NOT NULL,
    revision    bigint NOT NULL,
    op          text NOT NULL CHECK (op IN ('create', 'update', 'move', 'delete', 'restore')),
    snapshot    jsonb NOT NULL,
    device_id   uuid,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (block_id, revision)
);
CREATE INDEX idx_block_revisions_block ON block_revisions (block_id, revision DESC);

CREATE TABLE ink_pages (
    id          uuid PRIMARY KEY,                     -- generated by the client
    session_id  uuid NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    user_id     uuid NOT NULL,
    ordinal     integer NOT NULL DEFAULT 0,
    background  text NOT NULL DEFAULT 'blank' CHECK (background IN ('blank', 'lined', 'grid', 'dotted')),
    width       real NOT NULL DEFAULT 1240,
    height      real NOT NULL DEFAULT 1754,
    revision    bigint NOT NULL DEFAULT 1,
    layer_rev   bigint NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    deleted_at  timestamptz
);
CREATE INDEX idx_ink_pages_session ON ink_pages (session_id, ordinal) WHERE deleted_at IS NULL;
CREATE TRIGGER trg_ink_pages_updated BEFORE UPDATE ON ink_pages
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Vector ink, never flattened. `points` = stroke format v1 (see ink.rs).
CREATE TABLE ink_strokes (
    id           uuid PRIMARY KEY,                    -- generated by the client
    page_id      uuid NOT NULL REFERENCES ink_pages (id) ON DELETE CASCADE,
    session_id   uuid NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    user_id      uuid NOT NULL,
    tool         text NOT NULL CHECK (tool IN (
                     'pen', 'pencil', 'highlighter', 'rect', 'circle', 'line', 'text')),
    points       bytea NOT NULL,
    color        text NOT NULL DEFAULT '#FF000000',
    width        real NOT NULL DEFAULT 2,
    text         text,
    audio_ts_ms  bigint,
    device_id    uuid,
    revision     bigint NOT NULL DEFAULT 1,
    layer_rev    bigint NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    deleted_at   timestamptz
);
CREATE INDEX idx_ink_strokes_page ON ink_strokes (page_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_ink_strokes_sync ON ink_strokes (session_id, layer_rev);
CREATE TRIGGER trg_ink_strokes_updated BEFORE UPDATE ON ink_strokes
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Scheduled jobs (daily purge …) enqueue once per period.
ALTER TABLE jobs ADD COLUMN dedupe_key text;
CREATE UNIQUE INDEX ux_jobs_dedupe ON jobs (dedupe_key) WHERE dedupe_key IS NOT NULL;
